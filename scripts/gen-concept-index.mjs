/**
 * Emits src/data/generative-ai/conceptIndex.ts — the card-level fields for every concept.
 * Keeping these in the entry bundle lets category grids, prerequisite links and next/prev
 * labels render without pulling a category's full lesson payload.
 * Usage: node scripts/gen-concept-index.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';

const conceptDir = 'src/data/generative-ai/concepts';
const outFile = 'src/data/generative-ai/conceptIndex.ts';
const tmpRoot = '.tmp-index';

fs.rmSync(tmpRoot, { recursive: true, force: true });
fs.mkdirSync(tmpRoot, { recursive: true });

const files = fs.readdirSync(conceptDir).filter((f) => f.endsWith('.ts')).sort();
const summaries = [];

for (const file of files) {
  const source = fs.readFileSync(path.join(conceptDir, file), 'utf8');
  const js = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  const out = path.join(tmpRoot, file.replace(/\.ts$/, '.mjs'));
  fs.writeFileSync(out, js, 'utf8');

  const { concepts } = await import(pathToFileURL(path.resolve(out)).href);
  for (const c of concepts) {
    summaries.push({
      id: c.id,
      categoryId: c.categoryId,
      title: c.title,
      subtitle: c.subtitle,
      difficulty: c.difficulty,
      estimatedMinutes: c.estimatedMinutes,
    });
  }
}

fs.rmSync(tmpRoot, { recursive: true, force: true });

const body = summaries
  .map((s) => `  ${JSON.stringify(s)},`)
  .join('\n');

const contents = `// Generated by scripts/gen-concept-index.mjs — do not edit by hand.
import type { ConceptSummary } from '../../types/content';

export const conceptSummaries: ConceptSummary[] = [
${body}
];
`;

fs.writeFileSync(outFile, contents, 'utf8');
console.log(`Wrote ${summaries.length} summaries to ${outFile}`);
